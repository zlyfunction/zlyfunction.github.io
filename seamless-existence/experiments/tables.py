"""Human-readable answer tables, in graphics language.

Reads ``results/survey.json`` and writes ``results/answers.md``: for each genus,
the general rule and the explicit list of exceptions, with cone angles written as
multiples of pi and holonomy written as the subgroup of rotations that occurs.

Usage::

    PYTHONPATH=src python3 experiments/tables.py
"""

from __future__ import annotations

import json
import sys
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

HOLONOMY_WORDS = {
    "Z_4": "some loop has holonomy an odd multiple of pi/2",
    "2Z_4": "every holonomy is a multiple of pi, some one is exactly pi",
    "0": "every holonomy is trivial (a translation surface)",
}


def angle(quarter_turns: int) -> str:
    """Cone angle as a multiple of pi."""
    f = Fraction(quarter_turns, 2)
    if f.denominator == 1:
        return f"{f.numerator}pi" if f.numerator != 1 else "pi"
    return f"{f.numerator}/{f.denominator} pi"


def main() -> None:
    survey = json.loads((ROOT / "results" / "survey.json").read_text())
    rows = survey["rows"]
    cfg = survey["config"]

    lines = [
        "# Answers, in graphics language",
        "",
        "Generated by `experiments/tables.py` from `results/survey.json`.",
        "",
        "A holonomy signature is a set of cone angles (all multiples of `pi/2`)",
        "together with the cross-field rotations along a homology basis.  By the",
        "Reduction Lemma the rotations only matter through the subgroup of `Z_4`",
        "they generate together with the cone angles, so each row below is a",
        "complete case, not an example.",
        "",
        f"Range surveyed: genus {cfg['genera']}, at most {cfg['n_max']} cones,",
        f"orders bounded by {cfg['max_order']}.",
        "",
    ]

    for genus in cfg["genera"]:
        sub = [r for r in rows if r["genus"] == genus]
        if not sub:
            continue
        empty = [r for r in sub if r["prediction"] == "empty"]
        unknown = [r for r in sub if r["prediction"] == "unknown"]
        certified = [r for r in sub if r["outcome"] == "CERTIFIED"]
        lines += [
            f"## Genus {genus}",
            "",
            f"{len(sub)} cases in range; {len(certified)} realized by an explicit "
            f"square-tiled surface; {len(empty)} unrealizable; "
            f"{len(unknown)} not decided by the quoted literature.",
            "",
        ]
        if genus == 0:
            lines += [
                "**Rule: always realizable.**  On the sphere the holonomy is "
                "determined by the cone angles, and Troyanov's theorem gives the "
                "metric, so quadrangulability never fails.",
                "",
            ]
        elif genus == 1:
            lines += [
                "**Rule: realizable except the cases below**, plus the cone-free "
                "case: a torus with no cones is realizable only with trivial "
                "holonomy.  `docs/genus1.md` proves this list is complete for "
                "every number of cones, not just the surveyed range.",
                "",
            ]
        else:
            lines += [
                "**Rule: realizable iff the reduced stratum is non-empty** "
                "(Main Conjecture); no counterexample in range.",
                "",
            ]
        if empty:
            lines += [
                "| cone angles | cross-field holonomy | why |",
                "|---|---|---|",
            ]
            for r in empty:
                angles = ", ".join(angle(a) for a in r["angles_in_quarter_turns"])
                lines.append(
                    f"| {angles} | {HOLONOMY_WORDS[r['rho_subgroup']]} | {r['reason']} |"
                )
            lines.append("")
        if unknown:
            n_cert = sum(1 for r in unknown if r["outcome"] == "CERTIFIED")
            lines += [
                f"Undecided by the quoted literature ({n_cert} of {len(unknown)} "
                "certified by search); these are the strata of primitive "
                "4-differentials that milestone M1 has to settle:",
                "",
            ]
            for r in unknown[:5]:
                angles = ", ".join(angle(a) for a in r["angles_in_quarter_turns"])
                lines.append(
                    f"* {angles} -- primitive {r['differential_order']}-differential "
                    f"with orders {r['reduced_orders']}"
                )
            if len(unknown) > 5:
                lines.append(f"* ... and {len(unknown) - 5} more")
            lines.append("")

    out = ROOT / "results" / "answers.md"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
