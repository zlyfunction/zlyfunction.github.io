"""Survey the realizability of holonomy signatures, orbit by orbit.

For every genus and every small multiset of cone orders:

1. enumerate the ``MCG``-orbits (``mcg.verify_reduction_lemma`` confirms that
   ``image(rho)`` is a complete orbit invariant),
2. ask ``predict`` what the flat-surface literature says about the reduced
   stratum,
3. try to build a square-tiled certificate with a targeted annealing search.

The three answers are then cross-checked.  The interesting cells are

* ``CONTRADICTION`` -- predicted empty but a mesh was found: a bug here, or a
  misquoted theorem in ``predict``;
* ``CERTIFIED`` -- predicted unknown but a mesh was found: a new data point;
* ``OPEN`` -- predicted unknown and no mesh found: a research target;
* ``CONFIRMED-EMPTY`` -- predicted empty and no mesh found, as it should be.

Usage::

    PYTHONPATH=src python3 experiments/survey.py [--quick]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from seamless_existence.mcg import verify_reduction_lemma  # noqa: E402
from seamless_existence.predict import EMPTY, EXISTS, classify_orders  # noqa: E402
from seamless_existence.search import min_faces, search_target  # noqa: E402
from seamless_existence.signature import SUBGROUP_NAMES  # noqa: E402


def order_multisets(genus: int, n_max: int, max_order: int) -> list[tuple[int, ...]]:
    """Non-decreasing multisets of nonzero orders ``>= -3`` summing to ``4(2g-2)``."""
    target = 4 * (2 * genus - 2)
    values = [v for v in range(-3, max_order + 1) if v != 0]
    out: list[tuple[int, ...]] = []

    def rec(prefix: tuple[int, ...], start: int, remaining: int, slots: int) -> None:
        if slots == 0:
            if remaining == 0 and prefix:
                out.append(prefix)
            return
        for i in range(start, len(values)):
            v = values[i]
            # prune: the rest can contribute at most max_order * slots and at
            # least -3 * slots
            rest = remaining - v
            if rest > max_order * (slots - 1) or rest < -3 * (slots - 1):
                continue
            rec(prefix + (v,), i, rest, slots - 1)

    for n in range(1, n_max + 1):
        rec((), 0, target, n)
    return sorted(set(out), key=lambda t: (len(t), t))


def run(
    genera: list[int],
    n_max: int,
    max_order: int,
    iters: int,
    restarts: int,
    extra_regular: int,
) -> dict:
    rows = []
    lemma_checks = []
    for genus in genera:
        for orders in order_multisets(genus, n_max, max_order):
            if genus >= 1:
                chk = verify_reduction_lemma(genus, orders)
                lemma_checks.append(chk)
                assert chk["constant"] and chk["separating"], chk
            for sig, verdict in classify_orders(genus, orders):
                d = sig.rho_subgroup()
                target = (genus, tuple(sorted(orders)), d)
                mesh = search_target(
                    target,
                    extra_regular=extra_regular,
                    iters=iters,
                    restarts=restarts,
                )
                if verdict.status == EMPTY:
                    outcome = "CONTRADICTION" if mesh else "CONFIRMED-EMPTY"
                elif verdict.status == EXISTS:
                    outcome = "CERTIFIED" if mesh else "UNCERTIFIED"
                else:
                    outcome = "CERTIFIED" if mesh else "OPEN"
                rows.append(
                    {
                        "genus": genus,
                        "orders": list(orders),
                        "angles_in_quarter_turns": [m + 4 for m in orders],
                        "rho_subgroup": SUBGROUP_NAMES[d],
                        "differential_order": sig.differential_order,
                        "reduced_orders": list(sig.reduced_orders()),
                        "prediction": verdict.status,
                        "reason": verdict.reason,
                        "source": verdict.source,
                        "min_faces": min_faces(genus, orders),
                        "certificate_faces": mesh.n_faces if mesh else None,
                        "certificate_alpha": list(mesh.alpha) if mesh else None,
                        "outcome": outcome,
                    }
                )
    return {"rows": rows, "lemma_checks": lemma_checks}


def to_markdown(result: dict) -> str:
    rows = result["rows"]
    lines = [
        "# Realizability survey",
        "",
        "Generated by `experiments/survey.py`; see `docs/reduction.md` for what the",
        "columns mean.  `k` is the order of the reduced differential",
        "(`k = 4 / |generator of image(rho)|`), `mu` its orders, `N` the number of",
        "squares in the certificate (`-` = none found).",
        "",
        "| g | cone angles (x pi/2) | m | image(rho) | k | mu | prediction | N | outcome |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            "| {g} | {ang} | {m} | {im} | {k} | {mu} | {pred} | {n} | {out} |".format(
                g=r["genus"],
                ang=" ".join(str(a) for a in r["angles_in_quarter_turns"]),
                m=" ".join(f"{m:+d}" for m in r["orders"]),
                im=r["rho_subgroup"],
                k=r["differential_order"],
                mu=" ".join(f"{m:+d}" for m in r["reduced_orders"]),
                pred=r["prediction"],
                n=r["certificate_faces"] if r["certificate_faces"] else "-",
                out=r["outcome"],
            )
        )

    counts: dict[str, int] = {}
    for r in rows:
        counts[r["outcome"]] = counts.get(r["outcome"], 0) + 1
    lines += ["", "## Totals", ""]
    for key in sorted(counts):
        lines.append(f"* `{key}`: {counts[key]}")

    open_rows = [r for r in rows if r["outcome"] == "OPEN"]
    lines += ["", "## Open cells (no theory, no certificate)", ""]
    if not open_rows:
        lines.append("None in this range.")
    for r in open_rows:
        lines.append(
            f"* g={r['genus']} m={r['orders']} image(rho)={r['rho_subgroup']} "
            f"-> primitive {r['differential_order']}-differential with orders "
            f"{r['reduced_orders']}"
        )

    contradictions = [r for r in rows if r["outcome"] == "CONTRADICTION"]
    lines += ["", "## Contradictions (must be empty)", ""]
    lines.append("None." if not contradictions else "")
    for r in contradictions:
        lines.append(f"* {r}")
    return "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true", help="smaller sweep, weaker search")
    ap.add_argument("--out", default=str(ROOT / "results"))
    args = ap.parse_args()

    if args.quick:
        cfg = dict(genera=[0, 1, 2], n_max=3, max_order=6, iters=4000, restarts=2, extra_regular=2)
    else:
        cfg = dict(genera=[0, 1, 2, 3], n_max=4, max_order=8, iters=12000, restarts=3, extra_regular=3)

    result = run(**cfg)  # type: ignore[arg-type]
    result["config"] = cfg

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "survey.json").write_text(json.dumps(result, indent=1))
    (out / "survey.md").write_text(to_markdown(result))

    counts: dict[str, int] = {}
    for r in result["rows"]:
        counts[r["outcome"]] = counts.get(r["outcome"], 0) + 1
    print(f"{len(result['rows'])} orbits surveyed")
    for k in sorted(counts):
        print(f"  {k}: {counts[k]}")
    print(f"wrote {out / 'survey.md'} and {out / 'survey.json'}")


if __name__ == "__main__":
    main()
